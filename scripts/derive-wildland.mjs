// Development only: derive the escape router's wildland layer from the Glendale GIS MCP snapshot.
// Reads CAL FIRE's Fire Hazard Severity Zones (LRA, 2025 map) as saved by `make gis-fetch`, keeps the
// High and Very High zones, simplifies them (Douglas-Peucker) and writes src/evacuation/data/wildland.ts.
//   node scripts/derive-wildland.mjs [path/to/snapshot-folder]
// Default folder: the newest snapshot in the MCP's cache (macOS ~/Library/Caches, else ~/.cache).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

/** ~40 m at Glendale's latitude: finer than a street block, coarse enough to keep the bundle small. */
const TOLERANCE_DEGREES = 0.0004;
const DECIMALS = 5;
const KEEP = { "Very High": "very-high", High: "high" };

function newestSnapshot() {
  for (const cache of [join(homedir(), "Library/Caches/glendale-gis-mcp"), join(homedir(), ".cache/glendale-gis-mcp")]) {
    const dir = join(cache, "snapshots");
    if (!existsSync(dir)) continue;
    const dated = readdirSync(dir).filter((name) => /^\d{8}$/.test(name)).sort();
    if (dated.length) return join(dir, dated.at(-1));
  }
  console.error("No Glendale GIS snapshot found. Run `make gis-fetch` first, or pass the snapshot folder.");
  process.exit(1);
}

function perpendicular([x, y], [x1, y1], [x2, y2]) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const length = Math.hypot(dx, dy);
  if (length === 0) return Math.hypot(x - x1, y - y1);
  return Math.abs(dy * x - dx * y + x2 * y1 - y2 * x1) / length;
}

function simplify(points, tolerance) {
  if (points.length < 3) return points;
  let index = 0;
  let max = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const distance = perpendicular(points[i], points[0], points.at(-1));
    if (distance > max) { max = distance; index = i; }
  }
  if (max <= tolerance) return [points[0], points.at(-1)];
  return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)];
}

const round = (value) => Number(value.toFixed(DECIMALS));

/** Closed ring in, open ring out (first point not repeated); null when it collapses. */
function simplifyRing(ring) {
  const open = ring.slice(0, -1);
  // Split at the point farthest from the first, so the closed ring simplifies as two open chains.
  let far = 0;
  open.forEach(([x, y], i) => {
    if (Math.hypot(x - open[0][0], y - open[0][1]) > Math.hypot(open[far][0] - open[0][0], open[far][1] - open[0][1])) far = i;
  });
  const first = simplify(open.slice(0, far + 1), TOLERANCE_DEGREES);
  const second = simplify([...open.slice(far), open[0]], TOLERANCE_DEGREES);
  const points = [...first.slice(0, -1), ...second.slice(0, -1)].map(([x, y]) => [round(x), round(y)]);
  return points.length >= 3 ? points : null;
}

const folder = process.argv[2] ?? newestSnapshot();
const manifest = JSON.parse(readFileSync(join(folder, "manifest.json"), "utf8"));
const layer = manifest.layers.calfire_fhsz_lra;
const collection = JSON.parse(readFileSync(join(folder, layer.file), "utf8"));

const zones = [];
let before = 0;
let after = 0;
for (const feature of collection.features) {
  const severity = KEEP[feature.properties.FHSZ_Description];
  if (!severity) continue;
  const polygons = feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  for (const polygon of polygons) {
    const rings = polygon.map(simplifyRing);
    before += polygon.reduce((sum, ring) => sum + ring.length, 0);
    if (!rings[0]) continue;
    const kept = [rings[0], ...rings.slice(1).filter(Boolean)];
    after += kept.reduce((sum, ring) => sum + ring.length, 0);
    zones.push({ severity, rings: kept });
  }
}

const header = `/*
 * GENERATED by scripts/derive-wildland.mjs: do not edit by hand.
 *
 * CAL FIRE Fire Hazard Severity Zones, Local Responsibility Area (map dated March 24, 2025), High and
 * Very High classes only, from the Glendale GIS MCP snapshot (${manifest.generator}, built ${manifest.built_at};
 * layer fetched ${layer.fetched_at}, source last edited ${layer.source_last_edit}). Covers Glendale plus
 * ${layer.clip?.meters ?? 2000} m; outside that, the escape router knows nothing about the landscape.
 * Simplified with Douglas-Peucker at ${TOLERANCE_DEGREES}° (${before} → ${after} points).
 *
 * These zones rate the long-term hazard of the landscape (fuels, terrain, weather). They are not live fire
 * data or an evacuation map, and NonWildland (unzoned) areas are not safe from wildfire. The escape router
 * only uses them to prefer routes that leave the hills quickly.
 */
`;

const body = `import type { WildlandZone } from "../wildland";

export const WILDLAND_SOURCE = {
  publisher: "CAL FIRE",
  layer: ${JSON.stringify(layer.title)},
  url: ${JSON.stringify(layer.layer_url)},
  mapDate: "2025-03-24",
  sourceLastEdit: ${JSON.stringify(layer.source_last_edit)},
  fetchedAt: ${JSON.stringify(layer.fetched_at)},
} as const;

/** Rings are [longitude, latitude] pairs, open (the first point is not repeated); ring 0 is the outline, the rest holes. */
export const WILDLAND_ZONES: readonly WildlandZone[] = [
${zones.map((zone) => `  { severity: "${zone.severity}", rings: ${JSON.stringify(zone.rings)} },`).join("\n")}
];
`;

const out = "src/evacuation/data/wildland.ts";
writeFileSync(out, header + body);
console.log(`Wrote ${out}: ${zones.length} polygons, ${before} → ${after} points.`);
